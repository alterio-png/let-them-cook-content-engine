def write_private(path, value):
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
        json.dump(value, handle, indent=2, sort_keys=True)
        handle.write("\n")


def signup(auth_url, email, password):
    class NoRedirect(urllib.request.HTTPRedirectHandler):
        def redirect_request(self, *_args, **_kwargs):
            return None

    request = urllib.request.Request(auth_url + "/signup", method="POST",
        headers={"Content-Type": "application/json"},
        data=json.dumps({"email": email, "password": password}).encode())
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), NoRedirect())
    with opener.open(request, timeout=10) as response:
        result = json.load(response)
    # A real UUID generated by the official GoTrue service is mandatory.
    return str(UUID(result.get("user", result)["id"]))


def prepare_fixture_database(admin_dsn, database_name, root):
    """Internal SQL contracts only, separate from the actual GoTrue database.

    PostgreSQL roles belong to the cluster and already exist from official Auth
    preparation. Reuse those roles, while this separate database uses the
    historical auth.uid fixture and never claims hosted authentication proof.
    """
    if not database_name.startswith("g1_r0_") or not database_name.replace("_", "").isalnum():
        raise ValueError("disposable G1 fixture database name required")
    with psycopg.connect(admin_dsn, autocommit=True) as db:
        db.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(database_name)))
    fixture_dsn = make_conninfo(**{**conninfo_to_dict(admin_dsn), "dbname": database_name})
    with psycopg.connect(fixture_dsn) as db:
        db.execute("""CREATE SCHEMA auth;
            CREATE TABLE auth.users(id uuid PRIMARY KEY);
            CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE SET search_path='' AS
            $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
            REVOKE ALL ON SCHEMA auth FROM PUBLIC;
            REVOKE ALL ON FUNCTION auth.uid() FROM PUBLIC;
            GRANT USAGE ON SCHEMA auth TO authenticated;
            GRANT EXECUTE ON FUNCTION auth.uid() TO authenticated;
        """)
        for name in ("sql/001_schema.sql", "sql/002_g1_control_plane.sql", "sql/003_media_execution.sql",
                     "supabase/migrations/20261107123845_g3a_cloud_contracts.sql",
                     "supabase/migrations/20261107150813_shared_upload_authority.sql",
                     "supabase/migrations/20261108081746_local_browser_ingestion.sql"):
            db.execute((root / name).read_text(encoding="utf-8"))
    return fixture_dsn


def prepare(output, api_port, parent_pid, fixture_database=None):
    output = output.absolute()
    root = Path(__file__).resolve().parents[1]
    if output == root or root in output.parents or output.is_symlink():
        raise ValueError("laboratory evidence must be outside the checkout")
    info = output.stat()
    if not output.is_dir() or info.st_uid != os.getuid() or info.st_mode & 0o077:
        raise ValueError("laboratory directory must be private and owned")
    admin_dsn = local_dsn(os.environ["G3A_AUTH_ADMIN_DSN"])
    api_dsn = local_dsn(os.environ["G3A_API_DSN"])
    auth_url = os.environ["G3A_AUTH_URL"]
    if not auth_url.startswith("http://127.0.0.1:"):
        raise ValueError("local Auth URL required")
    issuer, jwt_secret = os.environ["G3A_AUTH_ISSUER"], os.environ["G3A_AUTH_JWT_SECRET"]
    signing_key = base64.b64encode(secrets.token_bytes(32)).decode("ascii")
    admin_info = conninfo_to_dict(admin_dsn)
    component_dsns = {}
    with psycopg.connect(admin_dsn) as db:
        if db.execute("SELECT to_regnamespace('g3br0_private')").fetchone()[0]:
            raise ValueError("G3B-R0 schema exists; a fresh laboratory is required")
        migration = root / "supabase/migrations/20261108081746_local_browser_ingestion.sql"
        db.execute(migration.read_text(encoding="utf-8"))
        for login, role in (("g3br0_worker_login", "engine_worker"),
                            ("g3br0_ingest_login", "g3br0_ingester"),
                            ("g3br0_monitor_login", "pg_read_all_stats")):
            password = secrets.token_urlsafe(32)
            db.execute(sql.SQL("CREATE ROLE {} LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE "
                               "NOREPLICATION NOBYPASSRLS PASSWORD {}").format(sql.Identifier(login), sql.Literal(password)))
            db.execute(sql.SQL("GRANT {} TO {}").format(sql.Identifier(role), sql.Identifier(login)))
            component_dsns[login] = make_conninfo(**{**admin_info, "user": login, "password": password})
        for login, maximum in ROLE_LIMITS.items():
            db.execute(sql.SQL("ALTER ROLE {} CONNECTION LIMIT {}").format(sql.Identifier(login), sql.Literal(maximum)))
        # Monitor explicitly SET LOCAL ROLE pg_read_all_stats per transaction;
        # no implicit inheritance, write/worker/schema-owner access is needed.
    for directory in ("objects", "scratch", "ingest-scratch", "synthetic", "logs"):
        (output / directory).mkdir(mode=0o700)
    LocalObjectStore(output / "objects")
    generated = demo(output / "synthetic", "demo")
    video, caption = Path(generated["video"]), Path(generated["caption"])
    for path, cap in ((video, 1048576), (caption, 65536)):
        path.chmod(0o600)
        if not 0 < path.stat().st_size <= cap:
            raise ValueError("synthetic fixture exceeds unchanged upload limits")
    media = inspect_media(video, Limits(max_bytes=1048576))
    validate_srt(caption)
    users, fixtures = [], []
    for index in (1, 2):
        email, password = f"r0-{index}-{secrets.token_hex(6)}@example.invalid", secrets.token_urlsafe(24) + "aA7!"
        user_id = signup(auth_url, email, password)
        org_id = str(uuid4())
        user = {"email": email, "password": password, "user_id": user_id,
                "organization_id": org_id, "org_id": org_id}
        fixture = {"id": f"g0-synthetic-org-{index}", "organization_id": org_id,
            "video_path": str(video), "caption_path": str(caption),
            "video_sha256": hashlib.sha256(video.read_bytes()).hexdigest(), "video_bytes": video.stat().st_size,
            "caption_sha256": hashlib.sha256(caption.read_bytes()).hexdigest(), "caption_bytes": caption.stat().st_size,
            "duration_ms": round(media["duration_seconds"] * 1000),
            "input_width": media["input_width"], "input_height": media["input_height"],
            "has_audio": media["has_audio"]}
        with psycopg.connect(admin_dsn) as db:
            db.execute("INSERT INTO public.organizations(id,name) VALUES(%s,%s)", (org_id, f"R0 synthetic organization {index}"))
            db.execute("INSERT INTO public.memberships(organization_id,user_id,role) VALUES(%s,%s,'editor')", (org_id, user_id))
            db.execute("INSERT INTO public.org_quotas(organization_id,max_jobs,max_active_jobs,max_duration_ms,max_bytes) "
                       "VALUES(%s,20,2,10000,1048576)", (org_id,))
            db.execute("INSERT INTO g3a1_private.upload_limits(organization_id,max_bytes,max_count,max_upload_bytes) "
                       "VALUES(%s,16777216,64,1048576)", (org_id,))
            provenance = {"source": "engine.cli.demo", "rights": "generated synthetic testsrc2 and sine", "phase": "G3B-R0-local"}
            db.execute("INSERT INTO g3br0_private.synthetic_allowlist(organization_id,fixture_id,video_sha256,video_bytes,"
                       "caption_sha256,caption_bytes,provenance) VALUES(%s,%s,%s,%s,%s,%s,%s)",
                       (org_id, fixture["id"], fixture["video_sha256"], fixture["video_bytes"],
                        fixture["caption_sha256"], fixture["caption_bytes"], Jsonb(provenance)))
        users.append(user)
        fixtures.append(fixture)
    manifest_path = output / "fixture-manifest.json"
    write_private(manifest_path, {"fixtures": fixtures})
    api_config = {"api_dsn": api_dsn, "auth_url": auth_url, "issuer": issuer, "jwt_secret": jwt_secret,
        "signing_key": signing_key, "store_root": str(output / "objects"), "fixture_manifest": str(manifest_path),
        "host": "127.0.0.1", "port": api_port, "metrics_path": str(output / "logs/api-events.jsonl")}
    worker_config = {"worker_dsn": component_dsns["g3br0_worker_login"],
        "ingest_dsn": component_dsns["g3br0_ingest_login"], "store_root": str(output / "objects"),
        "scratch_root": str(output / "scratch"), "ingest_scratch": str(output / "ingest-scratch"),
        "events_path": str(output / "logs/worker-events.jsonl"), "poll_seconds": 0.25}
    monitor_config = {"monitor_dsn": component_dsns["g3br0_monitor_login"], "parent_pid": parent_pid,
        "events_path": str(output / "logs/resource-samples.jsonl"), "interval_seconds": 0.25}
    test_config = {**api_config, **worker_config, "admin_dsn": admin_dsn,
        "monitor_dsn": component_dsns["g3br0_monitor_login"], "users": users, "fixtures": fixtures,
        "worker_config": str(output / "worker-config.json")}
    if fixture_database:
        test_config["fixture_dsn"] = prepare_fixture_database(admin_dsn, fixture_database, root)
    ready = {"url": f"http://127.0.0.1:{api_port}", "auth_url": auth_url, "users": users,
             "fixtures": fixtures, "fixture_manifest": str(manifest_path), "limits": {
                 "upload_bytes": 1048576, "job_seconds": 120, "download_bytes": 33554432,
                 "postgres_max_connections": 30, "role_connections": ROLE_LIMITS,
                 "physical_render_concurrency": 1}}
    for name, value in (("api-config.json", api_config), ("worker-config.json", worker_config),
                        ("monitor-config.json", monitor_config), ("test-config.json", test_config), ("public-ready.json", ready)):
        write_private(output / name, value)
    print("Prepared real Auth users, organization-specific synthetic allowlist and restricted local components", flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--port", type=int, required=True)
    parser.add_argument("--parent-pid", type=int, required=True)
    parser.add_argument("--fixture-database", help="separate disposable G1 auth.uid fixture database for --test")
    args = parser.parse_args()
    if not 1024 <= args.port <= 65535 or args.parent_pid < 1:
        parser.error("bounded nonprivileged port and valid parent PID required")
    prepare(args.output, args.port, args.parent_pid, args.fixture_database)


if __name__ == "__main__":
    main()
